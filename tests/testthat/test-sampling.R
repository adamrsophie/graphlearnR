test_that("neighbor sampling keeps seeds first and maps nodes back", {
  g <- dataset_karate()
  sg <- sample_neighbors(g, seeds = c(5, 1, 34), fanouts = c(3, 2), seed = 1)
  expect_s3_class(sg, "sampled_graph")
  expect_equal(sg$n_id[1:3], c(5L, 1L, 34L))
  expect_equal(sg$num_seeds, 3L)
  expect_equal(sg$hop[1:3], c(0L, 0L, 0L))
  expect_false(anyDuplicated(sg$n_id) > 0)
  orig <- g$edge_index[, sg$e_id, drop = FALSE]
  expect_equal(matrix(sg$n_id[sg$edge_index], nrow = 2), orig)
  expect_equal(sg$x, g$x[sg$n_id, ])
  expect_equal(sg$y, g$y[sg$n_id])
})

test_that("fanouts limit sampled incoming edges per node and hop", {
  g <- dataset_karate()
  sg <- sample_neighbors(g, seeds = 1:3, fanouts = 2, seed = 2)
  incoming <- table(sg$edge_index[2, ])
  expect_true(all(incoming <= 2))
  expect_true(all(sg$edge_index[2, ] %in% 1:3))
})

test_that("full fanout reproduces the exact k-hop computation graph", {
  g <- random_graph(n = 15, m = 40, f = 2, seed = 3)
  sg <- k_hop_subgraph(g, c(2, 7), 2)
  hop1 <- unique(g$edge_index[1, g$edge_index[2, ] %in% c(2, 7)])
  hop2 <- unique(g$edge_index[1, g$edge_index[2, ] %in% hop1])
  expect_setequal(sg$n_id, unique(c(2, 7, hop1, hop2)))
  expect_equal(sort(sg$e_id), which(g$edge_index[2, ] %in% c(2, 7, setdiff(hop1, c(2, 7)))))
})

test_that("a model on the full k-hop sample gives the full graph output for seeds", {
  skip_if_no_torch()
  torch::torch_manual_seed(1)
  g <- random_graph(n = 20, m = 60, f = 3, seed = 4)
  m <- gnn_model("sage", 3, 8, 2, num_layers = 2)
  m$eval()
  full <- as_mat(graphlearnR:::model_forward(m, graph_tensors(g)))
  seeds <- c(3, 11, 17)
  sg <- sample_neighbors(g, seeds, fanouts = c(-1, -1))
  sub <- as_mat(graphlearnR:::model_forward(m, graph_tensors(sg)))
  expect_equal(sub[1:3, ], full[seeds, ], tolerance = 1e-5)
})

test_that("sampling is reproducible and leaves the caller's RNG alone", {
  g <- dataset_karate()
  set.seed(1)
  before <- .Random.seed
  a <- sample_neighbors(g, 1:4, c(3, 3), seed = 10)
  b <- sample_neighbors(g, 1:4, c(3, 3), seed = 10)
  expect_identical(.Random.seed, before)
  expect_equal(a$n_id, b$n_id)
  expect_equal(a$e_id, b$e_id)
  c2 <- sample_neighbors(g, 1:4, c(3, 3), replace = TRUE, seed = 10)
  expect_true(all(table(c2$edge_index[2, c2$edge_index[2, ] %in% 1:4]) == 3))
  expect_error(sample_neighbors(g, 99, 2), "1:34")
  expect_error(sample_neighbors(g, c(1, 1), 2), "duplicates")
})

test_that("loaders split seeds and graphs into batches", {
  g <- split_nodes(dataset_karate(), seed = 1)
  ld <- node_loader(g, batch_size = 7, fanouts = c(2, 2), seed = 1)
  bs <- loader_batches(ld, 1)
  expect_length(bs, length(ld))
  expect_setequal(unlist(lapply(bs, function(b) b$n_id[seq_len(b$num_seeds)])), which(g$train_mask))
  expect_equal(loader_batches(ld, 1)[[1]]$n_id, bs[[1]]$n_id)
  expect_false(identical(loader_batches(ld, 2)[[1]]$n_id, bs[[1]]$n_id))
  gl <- graph_loader(dataset_synthetic_graphs(10, seed = 1), batch_size = 4, shuffle = FALSE)
  gb <- loader_batches(gl)
  expect_equal(unname(vapply(gb, function(b) b$num_graphs, integer(1))), c(4L, 4L, 2L))
})

test_that("negative sampling avoids positives, loops and duplicates", {
  pos <- rbind(c(1, 2, 3, 4), c(2, 3, 4, 1))
  neg <- negative_sampling(pos, num_nodes = 6, num_samples = 20, seed = 1)
  expect_equal(dim(neg), c(2, 20))
  key <- paste(neg[1, ], neg[2, ])
  expect_false(any(key %in% paste(pos[1, ], pos[2, ])))
  expect_false(any(neg[1, ] == neg[2, ]))
  expect_false(anyDuplicated(key) > 0)
  un <- negative_sampling(pos, num_nodes = 6, num_samples = 10, directed = FALSE, seed = 1)
  expect_true(all(un[1, ] < un[2, ]))
  bad <- c(paste(pos[1, ], pos[2, ]), paste(pos[2, ], pos[1, ]))
  expect_false(any(paste(un[1, ], un[2, ]) %in% bad))
  bip <- negative_sampling(rbind(1, 1), num_src = 2, num_dst = 3, num_samples = 5, seed = 1)
  expect_true(all(bip[1, ] <= 2 & bip[2, ] <= 3))
  expect_error(negative_sampling(rbind(1, 2), num_nodes = 2, num_samples = 5), "candidate")
})

test_that("corrupted tails exclude known positives", {
  pos <- rbind(c(1, 2), c(2, 3))
  known <- cbind(pos, rbind(1, 4))
  ct <- corrupt_tails(pos, num_nodes = 6, k = 3, known = known, seed = 1)
  expect_equal(dim(ct), c(2, 3))
  expect_false(any(ct[1, ] %in% c(2, 4)))
  expect_false(any(ct[2, ] == 3))
})
